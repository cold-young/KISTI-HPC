"""Literals from the pre-Gilbreth era that every other module is forbidden to spell.

AC-0.8 makes this module the **sole path allowlisted** from the AC-1.6 branding
ban and the AC-5.4 container-runtime ban.  The exemption is not a convenience:
two migration paths are *unresolvable by relocation*, because they have to
recognise a string in order to remove or reject it, and a rule that bans the
literal while also requiring its detection is a contradiction.  Putting both
literals in one path-exempted module resolves it, and has the second benefit of
giving both migrations a single place to be deleted from.

Consumers:

* :func:`rcac_cli.connect._remove_ssh_config` -- must match a block written by
  the pre-port CLI in a returning user's ``~/.ssh/config`` (AC-2.10, R17).
* :func:`rcac_cli.experiment.resolve_env_type` -- must recognise a legacy
  ``environment.type`` in an existing experiment YAML and fail with a message
  naming the replacement rather than silently selecting the template's
  host-python fallback branch (AC-5.9, wired in C4).  ``container.py`` was
  named here as a second consumer while C4 was unwritten; it turned out to
  need none -- it never reads a manifest -- so it is not listed.

**Deletion trigger.** Delete this module, its allowlist entry in
``tests/test_repo_hygiene.py``, and both consumers once no user is expected to
still be carrying a pre-port ``~/.ssh/config`` block or a pre-port experiment
YAML -- i.e. one full user-migration cycle after the Gilbreth port ships.
Nothing else in the tree may reference these values directly.
"""

from __future__ import annotations

from typing import Mapping

#: The SSH-config block marker written by the pre-port CLI.  Its End form is
#: the same string with "End " inserted; both are needed to bound the block.
LEGACY_SSH_MARKER = "# --- Neuron HPC (auto-generated by neuron-cli) ---"
LEGACY_SSH_END_MARKER = "# --- End Neuron HPC ---"

#: Legacy ``environment.type`` values mapped to their replacement.  Gilbreth
#: has Apptainer system-installed; the old runtime name is rejected rather
#: than silently aliased, so an existing YAML fails loudly and gets edited.
LEGACY_ENV_TYPES: Mapping[str, str] = {
    "singularity": "apptainer",
}
