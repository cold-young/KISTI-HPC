"""SSH ControlMaster session management for RCAC HPC."""

import os
import subprocess
import sys
from pathlib import Path

import click

from ._legacy import LEGACY_SSH_END_MARKER, LEGACY_SSH_MARKER
from .config import get_rcac_config, require_user
from .ssh import ssh_opt_argv, ssh_target

#: Bounds the block this CLI writes into ``~/.ssh/config``. The pair is
#: what makes the block removable (B11/AC-2.10) and must stay balanced.
SSH_CONFIG_MARKER = "# --- RCAC HPC (auto-generated by rcac-cli) ---"
SSH_CONFIG_END_MARKER = "# --- End RCAC HPC ---"

#: Every marker pair a user's ``~/.ssh/config`` may carry, newest first.
#: The legacy pair comes from :mod:`rcac_cli._legacy`; a returning user
#: still has an orphaned pre-port block pointing at the old cluster (R17).
MANAGED_MARKERS = (
    (SSH_CONFIG_MARKER, SSH_CONFIG_END_MARKER),
    (LEGACY_SSH_MARKER, LEGACY_SSH_END_MARKER),
)


def _get_socket_path(cfg: dict) -> Path:
    """Resolve the SSH control socket path."""
    control_path = cfg["ssh"]["control_path"]
    user = cfg["ssh"]["user"]
    host = cfg["ssh"]["login_host"]
    port = cfg["ssh"]["port"]
    resolved = control_path.replace("%r", user).replace("%h", host).replace("%p", str(port))
    return Path(os.path.expanduser(resolved))


def _ensure_socket_dir(socket_path: Path) -> None:
    """Ensure the socket directory exists."""
    socket_path.parent.mkdir(parents=True, exist_ok=True)


def _generate_ssh_config(cfg: dict) -> str:
    """Generate the managed SSH config block.

    Exactly **one** ``Host`` stanza (AC-2.12).  The second stanza this used to
    emit pointed at the old cluster's data-transfer node; Gilbreth documents
    none, so it is gone along with the config key that fed it.  The alias is
    ``gilbreth`` now that ``login_host`` actually resolves to Gilbreth --
    renaming it earlier would have produced ``Host gilbreth`` with a
    ``HostName`` from a different cluster.
    """
    ssh = cfg["ssh"]
    lines = [
        SSH_CONFIG_MARKER,
        "Host gilbreth",
        f"    HostName {ssh['login_host']}",
        f"    User {ssh['user']}",
        f"    Port {ssh['port']}",
        "    ControlMaster auto",
        f"    ControlPath {ssh['control_path']}",
        f"    ControlPersist {ssh['control_persist']}",
        f"    ServerAliveInterval {ssh['server_alive_interval']}",
        f"    ServerAliveCountMax {ssh['server_alive_count_max']}",
        SSH_CONFIG_END_MARKER,
    ]
    return "\n".join(lines)


def strip_managed_blocks(text: str) -> tuple[str, int]:
    """Remove every managed block from *text*; return the rest and the count.

    Removes the marker lines and everything between them, for both the current
    and the legacy marker pair.  Lines outside a block are returned **byte for
    byte** -- including the blank separators :func:`_write_ssh_config` adds --
    because this edits a file the user also hand-maintains.

    An unterminated block (the user deleted the End marker) is removed to end
    of file: leaving a half-block behind would make the config unwriteable by
    the next ``--setup-config`` and unreadable by ssh.
    """
    lines = text.splitlines(keepends=True)
    kept: list[str] = []
    removed = 0
    end_marker: str | None = None
    for line in lines:
        if end_marker is not None:
            if end_marker in line:
                end_marker = None
            continue
        opened = next(
            (end for begin, end in MANAGED_MARKERS if begin in line), None
        )
        if opened is not None:
            end_marker = opened
            removed += 1
            continue
        kept.append(line)
    return "".join(kept), removed


def _is_connected(cfg: dict) -> bool:
    """Check if a ControlMaster session is active."""
    socket = _get_socket_path(cfg)
    if not socket.exists():
        return False
    result = subprocess.run(
        ["ssh", "-O", "check", "-S", str(socket), f"{cfg['ssh']['user']}@{cfg['ssh']['login_host']}"],
        capture_output=True,
        text=True,
    )
    return result.returncode == 0


@click.command()
@click.option("--setup-config", is_flag=True, help="Write SSH config to ~/.ssh/config")
def connect(setup_config: bool) -> None:
    """Open an SSH ControlMaster session to RCAC (OTP required once)."""
    cfg = get_rcac_config()
    require_user(cfg)

    if setup_config:
        _write_ssh_config(cfg)
        return

    if _is_connected(cfg):
        click.echo("Already connected to RCAC.")
        return

    socket = _get_socket_path(cfg)
    _ensure_socket_dir(socket)

    ssh = cfg["ssh"]
    cmd = [
        "ssh",
        *ssh_opt_argv(cfg),
        "-N", "-f",  # background, no command
        ssh_target(cfg),
    ]

    click.echo(f"Connecting to {ssh['login_host']} as {ssh['user']}...")
    click.echo("Enter OTP when prompted.")
    result = subprocess.run(cmd)

    if result.returncode == 0:
        click.echo(f"Connected! Session will persist for {ssh['control_persist']}.")
    else:
        click.echo("Connection failed.", err=True)
        sys.exit(1)


def _write_ssh_config(cfg: dict) -> None:
    """Append the managed SSH config block to ~/.ssh/config."""
    ssh_config_path = Path.home() / ".ssh" / "config"

    if ssh_config_path.exists():
        existing = ssh_config_path.read_text()
        if SSH_CONFIG_MARKER in existing:
            click.echo(
                "RCAC SSH config already exists in ~/.ssh/config. "
                "Run `rcac-disconnect --remove-config` first to regenerate."
            )
            return
        # A returning user still carries the pre-port block, which aliases a
        # host on a cluster this CLI no longer talks to (R17). Drop it before
        # appending, so the two cannot both answer for the same alias.
        cleaned, removed = strip_managed_blocks(existing)
        if removed:
            ssh_config_path.write_text(cleaned)
            click.echo(f"Removed {removed} stale managed block(s) from {ssh_config_path}.")

    block = _generate_ssh_config(cfg)
    with open(ssh_config_path, "a") as f:
        f.write("\n\n" + block + "\n")

    ssh_config_path.chmod(0o600)
    click.echo(f"SSH config written to {ssh_config_path}")

    # Ensure socket directory exists
    socket = _get_socket_path(cfg)
    _ensure_socket_dir(socket)
    click.echo(f"Socket directory ensured: {socket.parent}")


@click.command()
def status() -> None:
    """Check current RCAC SSH connection status."""
    cfg = get_rcac_config()
    require_user(cfg)

    if _is_connected(cfg):
        click.echo("RCAC: CONNECTED")
    else:
        click.echo("RCAC: DISCONNECTED")


@click.command()
@click.option(
    "--remove-config",
    is_flag=True,
    help="Remove the managed block from ~/.ssh/config instead of closing the session",
)
def disconnect(remove_config: bool) -> None:
    """Close the RCAC SSH ControlMaster session."""
    cfg = get_rcac_config()
    require_user(cfg)

    if remove_config:
        _remove_ssh_config()
        return

    socket = _get_socket_path(cfg)
    if not socket.exists():
        click.echo("No active session found.")
        return

    result = subprocess.run(
        ["ssh", "-O", "exit", "-S", str(socket), f"{cfg['ssh']['user']}@{cfg['ssh']['login_host']}"],
        capture_output=True,
        text=True,
    )

    if result.returncode == 0:
        click.echo("Disconnected from RCAC.")
    else:
        click.echo(f"Disconnect failed: {result.stderr}", err=True)



def _remove_ssh_config() -> None:
    """Remove the managed block from ~/.ssh/config (B11, AC-2.10).

    The counterpart :func:`_write_ssh_config` never had: before this, a user
    who ran ``--setup-config`` could only undo it by hand-editing, and a user
    returning from the pre-port CLI kept a stale alias forever.
    """
    ssh_config_path = Path.home() / ".ssh" / "config"
    if not ssh_config_path.exists():
        click.echo(f"No SSH config at {ssh_config_path}; nothing to remove.")
        return

    cleaned, removed = strip_managed_blocks(ssh_config_path.read_text())
    if not removed:
        click.echo(f"No managed block found in {ssh_config_path}.")
        return

    ssh_config_path.write_text(cleaned)
    ssh_config_path.chmod(0o600)
    click.echo(f"Removed {removed} managed block(s) from {ssh_config_path}.")
