"""SSH ControlMaster session management for Gilbreth.

Gilbreth logins use the Purdue career-account password plus an MFA push
(or an SSH key). A ControlMaster socket lets you approve MFA once and reuse
the connection for every rsync / sbatch / squeue call afterwards.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import click

from .config import get_config, require_user
from .remote import is_connected, socket_path, ssh_target

MARKER_BEGIN = "# --- Gilbreth (auto-generated by gilbreth-cli) ---"
MARKER_END = "# --- End Gilbreth ---"


def generate_ssh_config(cfg: dict) -> str:
    ssh = cfg["ssh"]
    lines = [
        MARKER_BEGIN,
        "Host gilbreth",
        f"    HostName {ssh['login_host']}",
        f"    User {ssh['user']}",
        f"    Port {ssh['port']}",
        "    ControlMaster auto",
        f"    ControlPath {ssh['control_path']}",
        f"    ControlPersist {ssh['control_persist']}",
        f"    ServerAliveInterval {ssh['server_alive_interval']}",
        f"    ServerAliveCountMax {ssh['server_alive_count_max']}",
        MARKER_END,
    ]
    return "\n".join(lines)


def write_ssh_config(cfg: dict, ssh_config_path: Path | None = None) -> Path:
    path = ssh_config_path or Path.home() / ".ssh" / "config"
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    existing = path.read_text() if path.exists() else ""
    block = generate_ssh_config(cfg)

    if MARKER_BEGIN in existing:
        start = existing.index(MARKER_BEGIN)
        if MARKER_END in existing[start:]:
            end = existing.index(MARKER_END, start) + len(MARKER_END)
        else:  # truncated block from a previous edit: replace up to the next 'Host ' or EOF
            nxt = existing.find("\nHost ", start + 1)
            end = len(existing) if nxt == -1 else nxt
        updated = existing[:start] + block + existing[end:]
    else:
        updated = existing.rstrip("\n") + ("\n\n" if existing else "") + block + "\n"

    path.write_text(updated)
    path.chmod(0o600)
    socket_path(cfg).parent.mkdir(parents=True, exist_ok=True)
    return path


@click.command()
@click.option("--setup-config", is_flag=True, help="Write/refresh the 'Host gilbreth' block in ~/.ssh/config")
@click.option("--setup-key", is_flag=True, help="Install your SSH public key on Gilbreth (ssh-copy-id) so MFA is no longer needed")
@click.option("--identity", "-i", default=None, type=click.Path(), help="Public key to install (default: ~/.ssh/id_ed25519.pub or id_rsa.pub)")
def connect(setup_config: bool, setup_key: bool, identity: str | None) -> None:
    """Open a persistent SSH session to Gilbreth (password + MFA approved once)."""
    cfg = get_config()
    require_user(cfg)

    if setup_config:
        path = write_ssh_config(cfg)
        click.echo(f"SSH config written to {path} (Host gilbreth)")
        return

    if setup_key:
        _setup_key(cfg, identity)
        return

    if is_connected(cfg):
        click.echo("Already connected to Gilbreth.")
        return

    ssh = cfg["ssh"]
    socket_path(cfg).parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        "ssh",
        "-o", "ControlMaster=auto",
        "-o", f"ControlPath={ssh['control_path']}",
        "-o", f"ControlPersist={ssh['control_persist']}",
        "-o", f"ServerAliveInterval={ssh['server_alive_interval']}",
        "-o", f"ServerAliveCountMax={ssh['server_alive_count_max']}",
        "-p", str(ssh["port"]),
        "-N", "-f",
        ssh_target(cfg),
    ]
    click.echo(f"Connecting to {ssh['login_host']} as {ssh['user']} ...")
    click.echo("Enter your Purdue password, then approve the MFA push (skipped if an SSH key is installed).")
    result = subprocess.run(cmd, check=False)
    if result.returncode == 0:
        click.echo(f"Connected. Session persists for {ssh['control_persist']} (gilbreth-status to check).")
    else:
        click.echo("Connection failed.", err=True)
        sys.exit(1)


def _setup_key(cfg: dict, identity: str | None) -> None:
    candidates = [Path(identity)] if identity else [
        Path.home() / ".ssh" / "id_ed25519.pub",
        Path.home() / ".ssh" / "id_rsa.pub",
    ]
    pub = next((p for p in candidates if p.exists()), None)
    if pub is None:
        click.echo("No public key found. Create one first:\n  ssh-keygen -t ed25519", err=True)
        sys.exit(1)
    click.echo(f"Installing {pub} on Gilbreth (password + MFA required once) ...")
    result = subprocess.run(["ssh-copy-id", "-i", str(pub), "-p", str(cfg["ssh"]["port"]), ssh_target(cfg)], check=False)
    if result.returncode == 0:
        click.echo("Key installed. Future logins will not prompt for MFA.")
    else:
        click.echo("ssh-copy-id failed.", err=True)
        sys.exit(1)


@click.command()
def status() -> None:
    """Show whether the Gilbreth ControlMaster session is alive."""
    cfg = get_config()
    require_user(cfg)
    if is_connected(cfg):
        click.echo("Gilbreth: CONNECTED")
    else:
        click.echo("Gilbreth: DISCONNECTED")
        sys.exit(1)


@click.command()
def disconnect() -> None:
    """Close the Gilbreth ControlMaster session."""
    cfg = get_config()
    require_user(cfg)
    sock = socket_path(cfg)
    if not sock.exists():
        click.echo("No active session.")
        return
    result = subprocess.run(["ssh", "-O", "exit", "-S", str(sock), ssh_target(cfg)], capture_output=True, text=True, check=False)
    if result.returncode == 0:
        click.echo("Disconnected from Gilbreth.")
    else:
        click.echo(f"Disconnect failed: {result.stderr.strip()}", err=True)
        sys.exit(1)
